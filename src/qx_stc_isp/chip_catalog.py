@dataclass(frozen=True, slots=True)
class ChipDescriptor:
    name: str
    evidence_status: str
    program_bytes: int | None
    chip_id: int | None
    bootloader_family: str | None
    source: str
    alternate_chip_id: int | None = None

    @property
    def candidate_ids(self) -> tuple[int, ...]:
        return tuple(
            value for value in (self.chip_id, self.alternate_chip_id)
            if value is not None and value != 0
        )


@dataclass(frozen=True, slots=True)
class ChipCatalog:
    """只读、完整读取已定位识别表的目录；不自动启用硬件下载。"""

    entries: tuple[ChipDescriptor, ...]
    _by_name: Mapping[str, ChipDescriptor] = field(init=False, repr=False)

    def __post_init__(self) -> None:
        by_name = {entry.name: entry for entry in self.entries}
        if len(by_name) != len(self.entries):
            raise ValueError("chip names must be unique")
        object.__setattr__(self, "_by_name", MappingProxyType(by_name))

    @classmethod
    def from_static_evidence(cls) -> ChipCatalog:
        chips: list[ChipDescriptor] = []
        for index, line in enumerate(_STATIC_IDENTIFICATION_ROWS.splitlines(), 1):
            name, primary_hex, alternate_hex = line.split("|")
            chips.append(
                ChipDescriptor(
                    name=name,
                    evidence_status=EVIDENCE_STATUS,
                    program_bytes=None,
                    chip_id=int(primary_hex, 16),
                    alternate_chip_id=int(alternate_hex, 16) if alternate_hex else None,
                    bootloader_family=None,
                    source=f"AiCube v6.97A 静态识别表索引 {index}",
                )
            )
        if len(chips) != IDENTIFICATION_ENTRY_COUNT:
            raise ValueError("static identification table count changed")
        return cls(tuple(chips))

    def get(self, name: str) -> ChipDescriptor | None:
        return self._by_name.get(name)

